"""Checked Akış AST -> Python 3.11 source."""
from __future__ import annotations

from .checker import PY_RESERVED
from .types import NONE

RT_NAMES = {
    "print": "print_", "min": "min_", "max": "max_", "sum": "sum_", "len": "len_", "abs": "abs_",
    "round": "round_", "str": "str_", "int": "int_", "float": "float_", "range": "range_", "list": "list_",
    "dict": "dict_", "any": "any_", "all": "all_", "zip": "zip_", "enumerate": "enumerate_", "chr": "chr_",
    "ord": "ord_",
}

BINPREC = {"**": 8, "*": 7, "/": 7, "//": 7, "%": 7, "+": 6, "-": 6}


def rt(name):
    return "_rt." + RT_NAMES.get(name, name)


def pyident(name):
    return name + "_" if name in PY_RESERVED else name


class Gen:
    def __init__(self, filename):
        self.filename = filename
        self.out = []

    def line(self, depth, text):
        self.out.append("    " * depth + text)

    def module(self, mod):
        self.line(0, f"# generated by akis from {self.filename}; do not edit")
        self.line(0, "import akis_rt as _rt")
        self.line(0, "")
        for it in mod.items:
            if it.kind == "Use":
                mod_path = ".".join(it.path[:-1])
                wrap = "True" if it.sig.ret.__class__.__name__ == "Err" else "False"
                self.line(0, f"{it.sig.pyname} = _rt.py_import({mod_path!r}, {it.path[-1]!r}, errors={wrap})")
            elif it.kind == "TypeDecl":
                fields = ", ".join(f[0] for f in it.fields)
                self.line(0, f"# type {it.name} = record({fields}) -> dict")
        for it in mod.items:
            if it.kind == "Fn":
                self.line(0, "")
                self.fn(it)
        return "\n".join(self.out) + "\n"

    def fn(self, f):
        params = ", ".join(p.pyname for p in f.params)
        self.line(0, f"def {f.name}({params}):")
        self.ret_none = f.ret_t == NONE
        self.block(f.body, 1, tail=True)

    def block(self, stmts, depth, tail=False):
        for i, s in enumerate(stmts):
            self.stmt(s, depth, tail and i == len(stmts) - 1)

    def stmt(self, s, d, tail):
        k = s.kind
        if k == "Let":
            self.line(d, f"{s.pyname} = {self.e(s.value)}")
        elif k == "LetMulti":
            self.line(d, f"{', '.join(s.pynames)} = {self.e(s.value)}")
        elif k == "Assign":
            self.line(d, f"{self.target(s.target)} = {self.e(s.value)}")
        elif k == "AssignMulti":
            self.line(d, f"{', '.join(self.target(t) for t in s.targets)} = {self.e(s.value)}")
        elif k == "AugAssign":
            t = self.target(s.target)
            self.line(d, f"{t} = ({self.e(s.target)} {s.op[:-1]} {self.e(s.value)})")
        elif k == "Break":
            self.line(d, "break")
        elif k == "Continue":
            self.line(d, "continue")
        elif k == "Return":
            self.line(d, "return" if s.value is None else f"return {self.e(s.value)}")
        elif k == "ExprStmt":
            if tail and not self.ret_none:
                self.line(d, f"return {self.e(s.expr)}")
            else:
                self.line(d, self.e(s.expr))
        elif k == "If":
            for i, (cond, body) in enumerate(s.branches):
                self.line(d, f"{'if' if i == 0 else 'elif'} {self.e(cond)}:")
                self.block(body, d + 1, tail)
            if s.else_body is not None:
                self.line(d, "else:")
                self.block(s.else_body, d + 1, tail)
        elif k == "For":
            self.line(d, f"for {', '.join(s.pynames)} in {self.e(s.iter)}:")
            self.block(s.body, d + 1)
        elif k == "While":
            self.line(d, f"while {self.e(s.cond)}:")
            self.block(s.body, d + 1)
        else:
            raise AssertionError(f"cannot generate {k}")

    def target(self, t):
        if t.kind == "Var":
            return t.pyname
        if t.kind == "Index":
            return f"{self.e(t.obj)}[{self.e(t.idx)}]"
        if t.kind == "Field":
            return f"{self.e(t.obj)}[{t.name!r}]"
        raise AssertionError(t.kind)

    # ---- expressions (always fully parenthesised where precedence matters)
    def e(self, n):
        return getattr(self, "g_" + n.kind)(n)

    def g_Int(self, n):
        return repr(n.value)

    def g_Float(self, n):
        return repr(n.value)

    def g_Bool(self, n):
        return "True" if n.value else "False"

    def g_NoneLit(self, n):
        return "None"

    def g_Str(self, n):
        if all(isinstance(p, str) for p in n.parts):
            return repr("".join(n.parts))
        pieces = [repr(p) if isinstance(p, str) else f"_rt.show({self.e(p)})" for p in n.parts]
        return "(" + " + ".join(pieces) + ")"

    def g_It(self, n):
        return "it"

    def g_Var(self, n):
        return n.pyname

    def call_args(self, args, pre=None):
        parts = [] if pre is None else [pre]
        for k, a in args:
            parts.append(self.e(a) if k is None else f"{pyident(k)}={self.e(a)}")
        return ", ".join(parts)

    def callee(self, n):
        kind, name = n.target
        if kind == "builtin":
            return rt(name)
        return name

    def g_Call(self, n):
        if n.target[0] == "record":
            given = {k: a for k, a in n.args}
            items = ", ".join(f"{k!r}: {self.e(given[k])}" for k in n.fields_order if k in given)
            return "{" + items + "}"
        return f"{self.callee(n)}({self.call_args(n.args)})"

    def g_Tuple(self, n):
        items = [self.e(x) for x in n.items]
        return "(" + items[0] + ",)" if len(items) == 1 else "(" + ", ".join(items) + ")"

    def g_List(self, n):
        return "[" + ", ".join(self.e(x) for x in n.items) + "]"

    def g_Dict(self, n):
        return "{" + ", ".join(f"{self.e(k)}: {self.e(v)}" for k, v in n.pairs) + "}"

    def g_Field(self, n):
        return f"{self.e(n.obj)}[{n.name!r}]"

    def g_TIndex(self, n):
        return f"{self.e(n.obj)}[{n.idx}]"

    def g_Index(self, n):
        return f"_rt.at({self.e(n.obj)}, {self.e(n.idx)})"

    def g_Slice(self, n):
        lo = "" if n.lo is None else self.e(n.lo)
        hi = "" if n.hi is None else self.e(n.hi)
        return f"{self.e(n.obj)}[{lo}:{hi}]"

    def g_ListComp(self, n):
        cond = "" if n.cond is None else f" if {self.e(n.cond)}"
        return f"[{self.e(n.expr)} for {', '.join(n.pynames)} in {self.e(n.iter)}{cond}]"

    def g_Format(self, n):
        return f"_rt.fmt({self.e(n.expr)}, {n.spec!r})"

    def g_MethodCall(self, n):
        return f"{self.callee(n)}({self.call_args(n.args, pre=self.e(n.obj))})"

    def g_Try(self, n):
        return self.e(n.expr)  # errors are exceptions: propagation is automatic

    def g_Coalesce(self, n):
        return f"_rt.coalesce(lambda: {self.e(n.left)}, lambda: {self.e(n.right)})"

    def g_BoolOp(self, n):
        return f"({self.e(n.left)} {n.op} {self.e(n.right)})"

    def g_Not(self, n):
        return f"(not {self.e(n.expr)})"

    def g_Compare(self, n):
        s = self.e(n.first)
        for op, r in n.rest:
            s += f" {op} {self.e(r)}"
        return "(" + s + ")"

    def g_Bin(self, n):
        return f"({self.e(n.left)} {n.op} {self.e(n.right)})"

    def g_Unary(self, n):
        return f"({n.op}{self.e(n.expr)})"

    def g_IfExpr(self, n):
        return f"({self.e(n.then)} if {self.e(n.cond)} else {self.e(n.other)})"

    def g_Pipe(self, n):
        cur = self.e(n.head)
        for st in n.stages:
            cur = self.stage(st, cur)
        return cur

    def stage(self, st, cur):
        k = st.kind
        if k == "SCall":
            code = f"{self.callee(st)}({self.call_args(st.args, pre=cur)})"
            if st.default is not None:
                code = f"_rt.coalesce(lambda: {code}, lambda: {self.e(st.default)})"
            return code
        lam = f"lambda it: {self.e(st.expr)}"
        if k == "SWhere":
            return f"_rt.where({cur}, {lam})"
        if k == "SMap":
            return f"_rt.map_({cur}, {lam})"
        if k == "SSortBy":
            return f"_rt.sort_by({cur}, {lam}, {st.desc})"
        if k == "SCountBy":
            return f"_rt.count_by({cur}, {lam})"
        if k == "SGroupBy":
            return f"_rt.group_by({cur}, {lam})"
        if k == "STake":
            return f"_rt.take({cur}, {self.e(st.expr)})"
        if k == "SSkip":
            return f"_rt.skip({cur}, {self.e(st.expr)})"
        if k == "SMaxBy":
            return f"_rt.max_by({cur}, {lam})"
        if k == "SMinBy":
            return f"_rt.min_by({cur}, {lam})"
        raise AssertionError(k)


def generate(module, filename="sol.aks"):
    return Gen(filename).module(module)
